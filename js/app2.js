  const langInfo = () => LANGS.find((l) => l.id === lang) || LANGS[0];

  /** Build a regex that finds the word (or its first content word, with common endings) in a sentence. */
  function wordRegex(word) {
    const clean = String(word).replace(/\(.*?\)/g, '').replace(/\bsb\b|\bsth\b|someone|something/gi, '').trim();
    const parts = clean.split(/\s+/).filter(Boolean);
    if (!parts.length) return null;
    const stem = (p) => {
      let s = reRx(p.toLowerCase());
      if (s.length > 4) s = s.replace(/(e|y)$/, '');
      return s + "[a-z']*";
    };
    const body = parts.map(stem).join("[\\s-]+(?:[a-z']+[\\s-]+)?");
    return new RegExp('\\b' + body, 'i');
  }
  function highlight(sentence, word) {
    const rx = wordRegex(word);
    const s = esc(sentence);
    if (!rx) return s;
    return s.replace(rx, (m) => '<mark>' + m + '</mark>');
  }


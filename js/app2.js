  function runGame(pane, id, vocab, scope) {
    const back = () => practicePane(pane, vocab, scope);
    if (id === 'match') return matchGame(pane, vocab, back);
    const scopeOf = (w) => w._scope || scope;
    let pool = vocab;
    if (id === 'gap') pool = vocab.filter((w) => w.example && wordRegex(w.word) && wordRegex(w.word).test(w.example));
    if (id === 'trans') pool = vocab.filter((w) => trOf(w));
    if (pool.length < 4) { toast('Not enough words for this game'); return; }
    const qs = sample(pool, Math.min(10, pool.length));
    let n = 0, score = 0;
    const missed = [];
    const next = () => {
      if (n >= qs.length) return finish();
      const w = qs[n];
      const others = sample(vocab.filter((x) => x.word.toLowerCase() !== w.word.toLowerCase()), 3);
      const opts = shuffle([w, ...others]);
      let label, prompt;
      if (id === 'mean') { label = 'Which word means…'; prompt = esc(w.def); }
      else if (id === 'gap') { label = 'Fill the gap'; prompt = esc(w.example).replace(wordRegex(w.word), '<span class="gap">&nbsp;</span>'); }
      else if (id === 'trans') { const t = trOf(w); label = langInfo().name + ' → English'; prompt = '<span ' + (langInfo().rtl ? 'dir="rtl"' : '') + '>' + esc(t.w) + '</span>'; }
      else if (id === 'spell') { label = 'Listen and type the word'; prompt = '<button class="btn primary" id="hear">🔊 Play again</button><div class="note" style="margin-top:10px">Hint: ' + esc(w.def) + '</div>'; }

      pane.innerHTML = '<div class="quiz"><div class="q-top"><button class="btn sm ghost" id="quit">✕</button><div class="bar"><i style="width:' + (n / qs.length) * 100 + '%"></i></div><span class="q-score">' + score + ' / ' + qs.length + '</span></div>' +
        '<div class="q-card"><div class="q-label">' + label + ' · ' + (n + 1) + '/' + qs.length + '</div><div class="q-prompt">' + prompt + '</div>' +
        (id === 'spell' ? '<input class="spell-input" id="sp" autocomplete="off" autocapitalize="off" spellcheck="false" placeholder="Type here…"><div class="q-next"><button class="btn primary" id="check">Check</button></div>'
          : '<div class="opts">' + opts.map((o, k) => '<button class="opt" data-k="' + k + '">' + esc(o.word) + '</button>').join('') + '</div>') +
        '<div id="after"></div></div></div>';
      $('#quit', pane).onclick = back;
      const after = (ok) => {
        if (ok) score++; else { missed.push(w); setKnown(scopeOf(w), w, false); }
        $('#after', pane).innerHTML = '<div class="q-why">' + (ok ? '✅ ' : '❌ ') + '<b>' + esc(w.word) + '</b>: ' + esc(w.def) + '</div>' +
          '<div class="q-next"><button class="btn primary" id="nx">' + (n + 1 < qs.length ? 'Next →' : 'See result') + '</button></div>';
        const nx = $('#nx', pane); nx.focus(); nx.onclick = () => { n++; next(); };
      };
      if (id === 'spell') {
        const say = () => speak(w.word, null, 0.85);
        setTimeout(say, 250);
        $('#hear', pane).onclick = say;
        const inp = $('#sp', pane); inp.focus();
        const check = () => {
          const norm = (s) => s.toLowerCase().replace(/[^a-z]/g, '');
          const ok = norm(inp.value) === norm(w.word);
          inp.classList.add(ok ? 'right' : 'wrong'); inp.disabled = true; $('#check', pane).remove();
          after(ok);
        };
        $('#check', pane).onclick = check;
        inp.addEventListener('keydown', (e) => { if (e.key === 'Enter') check(); });
      } else {
        $$('.opt', pane).forEach((b) => b.addEventListener('click', () => {
          const pick = opts[+b.dataset.k];
          const ok = pick === w;
          $$('.opt', pane).forEach((x) => { x.disabled = true; if (opts[+x.dataset.k] === w) x.classList.add('right'); });
          if (!ok) b.classList.add('wrong');
          speak(w.word);
          after(ok);
        }));
      }
    };
    const finish = () => {
      if (score / qs.length >= 0.7) confetti();
      pane.innerHTML = '<div class="quiz"><div class="q-card result"><div class="score">' + score + '/' + qs.length + '</div><h2>' +
        (score === qs.length ? 'Perfect! 🌟' : score / qs.length >= 0.7 ? 'Great work! 💪' : 'Keep going, you’re learning! 🌱') + '</h2>' +
        (missed.length ? '<p class="note">Words to look at again (added to “Still learning”):</p><ul>' + missed.map((w) => '<li><b>' + esc(w.word) + '</b>: ' + esc(w.def) + '</li>').join('') + '</ul>' : '') +
        '<div class="toolbar" style="justify-content:center"><button class="btn primary" id="again">Play again</button><button class="btn" id="games">All games</button></div></div></div>';
      $('#again', pane).onclick = () => runGame(pane, id, vocab, scope);
      $('#games', pane).onclick = back;
    };
    next();
  }

  function matchGame(pane, vocab, back) {
    let round = 0, mistakes = 0;
    const rounds = 3;
    const start = performance.now();
    const play = () => {
      if (round >= rounds) {
        const secs = Math.round((performance.now() - start) / 1000);
        confetti();
        pane.innerHTML = '<div class="quiz"><div class="q-card result"><div class="score">' + secs + 's</div><h2>All pairs matched!</h2><p class="note">' + mistakes + ' mistake' + (mistakes === 1 ? '' : 's') + '</p>' +
          '<div class="toolbar" style="justify-content:center"><button class="btn primary" id="again">Play again</button><button class="btn" id="games">All games</button></div></div></div>';
        $('#again', pane).onclick = () => matchGame(pane, vocab, back);
        $('#games', pane).onclick = back;
        return;
      }
      const set = sample(vocab, Math.min(5, vocab.length));
      const left = shuffle(set), right = shuffle(set);
      pane.innerHTML = '<div class="quiz"><div class="q-top"><button class="btn sm ghost" id="quit">✕</button><div class="bar"><i style="width:' + (round / rounds) * 100 + '%"></i></div><span class="q-score">Round ' + (round + 1) + '/' + rounds + '</span></div>' +
        '<div class="match"><div class="col">' + left.map((w, k) => '<button class="m-item word" data-l="' + k + '">' + esc(w.word) + '</button>').join('') + '</div>' +
        '<div class="col">' + right.map((w, k) => '<button class="m-item" data-r="' + k + '">' + esc(w.def) + '</button>').join('') + '</div></div></div>';
      $('#quit', pane).onclick = back;
      let selL = null, selR = null, done = 0;
      const tryMatch = () => {
        if (selL == null || selR == null) return;
        const a = $('[data-l="' + selL + '"]', pane), b = $('[data-r="' + selR + '"]', pane);
        if (left[selL] === right[selR]) {
          a.classList.add('done'); b.classList.add('done'); speak(left[selL].word);
          if (++done === set.length) { round++; setTimeout(play, 600); }
        } else {
          mistakes++; a.classList.add('wrong'); b.classList.add('wrong');
          setTimeout(() => { a.classList.remove('wrong', 'sel'); b.classList.remove('wrong', 'sel'); }, 400);
        }
        a.classList.remove('sel'); b.classList.remove('sel'); selL = selR = null;
      };
      $$('[data-l]', pane).forEach((b) => b.onclick = () => { $$('[data-l]', pane).forEach((x) => x.classList.remove('sel')); b.classList.add('sel'); selL = +b.dataset.l; tryMatch(); });
      $$('[data-r]', pane).forEach((b) => b.onclick = () => { $$('[data-r]', pane).forEach((x) => x.classList.remove('sel')); b.classList.add('sel'); selR = +b.dataset.r; tryMatch(); });
    };
    play();
  }


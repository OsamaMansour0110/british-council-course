  function storyView(id) {
    const s = C.stories.find((x) => x.id === id);
    if (!s) return notFound();
    const d = findDeck('st:' + id);
    const read = (pane) => {
      const vocab = s.vocab.slice().sort((a, b) => b.word.length - a.word.length);
      const mark = (p) => {
        let html = esc(p);
        const used = new Set();
        vocab.forEach((w, wi) => {
          if (used.has(w.word)) return;
          const rx = wordRegex(w.word);
          if (!rx) return;
          // only replace outside existing tags
          html = html.replace(/(<[^>]+>)|([^<]+)/g, (m, tag, txt) => {
            if (tag || used.has(w.word)) return m;
            return txt.replace(rx, (hit) => { used.add(w.word); return '<span class="vw" data-vw="' + wi + '" tabindex="0" role="button">' + hit + '</span>'; });
          });
        });
        return html;
      };
      pane.innerHTML = '<div class="reader"><div class="toolbar"><button class="btn primary sm" id="readAll">▶ Read aloud</button><button class="btn sm" id="stop">■ Stop</button>' +
        (s.url ? '<a class="pill-link" href="' + esc(s.url) + '" target="_blank" rel="noopener">Original on British Council ↗</a>' : '') + '</div>' +
        s.paragraphs.map((p, i) => '<p data-p="' + i + '">' + mark(p) + '</p>').join('') + '</div>' +
        ((s.quotes || []).length ? '<div class="section-title"><h2>Memorable lines</h2></div><div class="phrases">' + s.quotes.slice(0, 12).map((q) => {
          const en = q.en || q.text || q.quote || ''; const ar = q.ar || q.arabic || '';
          return '<div class="phrase"><div><b>' + esc(en) + '</b>' + (ar ? '<small dir="rtl" class="rtl">' + esc(ar) + '</small>' : '') + '</div><button class="speak" data-say="' + esc(en) + '">🔊</button></div>';
        }).join('') + '</div>' : '');
      pane.addEventListener('click', (e) => {
        const v = e.target.closest('[data-vw]');
        if (v) openSheet(wordCardHTML(vocab[+v.dataset.vw], d.scope));
      });
      let stop = false;
      $('#readAll', pane).onclick = () => {
        stop = false;
        const ps = $$('[data-p]', pane);
        const go = (k) => {
          ps.forEach((p) => p.classList.remove('reading'));
          if (stop || k >= ps.length) return;
          ps[k].classList.add('reading'); ps[k].scrollIntoView({ behavior: 'smooth', block: 'center' });
          const u = speak(ps[k].textContent);
          if (u) u.onend = () => go(k + 1);
        };
        go(0);
      };
      $('#stop', pane).onclick = () => { stop = true; speechSynthesis.cancel(); $$('[data-p]', pane).forEach((p) => p.classList.remove('reading')); };
    };
    mountDeck(d, 'stories', { summary: s.summary, firstTabs: [{ id: 'read', label: '📖 Read', render: read }], links: s.author ? '<span class="note">' + esc(s.author) + '</span>' : '' });
  }

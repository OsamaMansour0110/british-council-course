  let voice = null;
  function pickVoice() {
    if (!('speechSynthesis' in window)) return;
    const vs = speechSynthesis.getVoices();
    voice = vs.find((v) => /en-GB/i.test(v.lang) && /Google|Natural|Libby|Sonia|Ryan/i.test(v.name)) || vs.find((v) => /en-GB/i.test(v.lang)) || vs.find((v) => /^en/i.test(v.lang)) || null;
  }
  if ('speechSynthesis' in window) { pickVoice(); speechSynthesis.onvoiceschanged = pickVoice; }
  function speak(text, btn, rate = 0.92) {
    if (!('speechSynthesis' in window)) { toast('Speech is not supported in this browser'); return; }
    speechSynthesis.cancel();
    const u = new SpeechSynthesisUtterance(text);
    if (voice) u.voice = voice;
    u.lang = voice ? voice.lang : 'en-GB';
    u.rate = rate;
    if (btn) { btn.classList.add('talking'); u.onend = u.onerror = () => btn.classList.remove('talking'); }
    speechSynthesis.speak(u);
    return u;
  }

  /* ---------- toast + confetti ---------- */
  let toastT;
  function toast(msg) {
    const t = $('#toast');
    t.textContent = msg; t.classList.add('on');
    clearTimeout(toastT); toastT = setTimeout(() => t.classList.remove('on'), 2200);
  }
  function confetti(n = 140) {
    if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    const cv = $('#confetti'), ctx = cv.getContext('2d');
    cv.width = innerWidth * devicePixelRatio; cv.height = innerHeight * devicePixelRatio;
    ctx.scale(devicePixelRatio, devicePixelRatio);
    const cols = ['#5b4bff', '#ff7a59', '#14a06b', '#f59e0b', '#e5484d', '#38bdf8'];
    const ps = Array.from({ length: n }, () => ({
      x: innerWidth / 2 + (Math.random() - 0.5) * 200, y: innerHeight * 0.35, vx: (Math.random() - 0.5) * 14, vy: -Math.random() * 14 - 4,
      r: Math.random() * 6 + 4, c: cols[(Math.random() * cols.length) | 0], a: Math.random() * 6, va: (Math.random() - 0.5) * 0.3,
    }));
    let f = 0;
    (function tick() {
      ctx.clearRect(0, 0, innerWidth, innerHeight);
      ps.forEach((p) => {
        p.vy += 0.35; p.vx *= 0.99; p.x += p.vx; p.y += p.vy; p.a += p.va;
        ctx.save(); ctx.translate(p.x, p.y); ctx.rotate(p.a); ctx.fillStyle = p.c; ctx.fillRect(-p.r / 2, -p.r / 4, p.r, p.r / 2); ctx.restore();
      });
      if (++f < 160) requestAnimationFrame(tick); else ctx.clearRect(0, 0, innerWidth, innerHeight);
    })();
  }

  /* ---------- scratch-to-reveal ---------- */
  function trOf(w) {
    const t = (w.tr && w.tr[lang]) || null;
    if (t) return t;
    // fallback for any old entry without translations
    if (lang === 'ar' && (w.arWord || w.arabic)) return { w: w.arWord || w.arabic, d: w.arMeaning || '' };
    return null;
  }
  function scratchHTML(w) {
    const t = trOf(w);
    const L = langInfo();
    if (!t) return '<div class="note">No ' + esc(L.name) + ' translation yet.</div>';
    return '<div class="scratch" data-scratch><div class="scratch-content" ' + (L.rtl ? 'dir="rtl" lang="ar"' : 'lang="' + L.id + '"') + '>' +
      '<span class="tw">' + esc(t.w) + '</span>' + (t.d ? '<span class="td">' + esc(t.d) + '</span>' : '') + '</div></div>';
  }
  function cssVar(n) { return getComputedStyle(document.documentElement).getPropertyValue(n).trim(); }

  function initScratch(el) {
    if (el._init) return; el._init = true;
    const cv = document.createElement('canvas');
    el.appendChild(cv);
    const ctx = cv.getContext('2d', { willReadFrequently: true });
    let w = 0, h = 0, dpr = 1, drawing = false, moved = 0, last = null, revealed = false, checks = 0;

    function paint() {
      const r = el.getBoundingClientRect();
      if (!r.width) return;
      dpr = Math.min(devicePixelRatio || 1, 2);
      w = r.width; h = r.height;
      cv.width = w * dpr; cv.height = h * dpr;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      const g = ctx.createLinearGradient(0, 0, w, h);
      g.addColorStop(0, cssVar('--foil-1')); g.addColorStop(0.5, cssVar('--foil-2')); g.addColorStop(1, cssVar('--foil-1'));
      ctx.globalCompositeOperation = 'source-over';
      ctx.fillStyle = g; ctx.fillRect(0, 0, w, h);
      // subtle diagonal shimmer lines
      ctx.strokeStyle = 'rgba(255,255,255,.25)'; ctx.lineWidth = 1;
      for (let x = -h; x < w; x += 9) { ctx.beginPath(); ctx.moveTo(x, h); ctx.lineTo(x + h, 0); ctx.stroke(); }
      ctx.fillStyle = cssVar('--foil-ink');
      ctx.font = '600 13.5px Inter, system-ui, sans-serif'; ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
      const L = langInfo();
      ctx.fillText('✨ Scratch or tap to see ' + L.name, w / 2, h / 2);
    }
    paint();
    new ResizeObserver(() => { if (!revealed) paint(); }).observe(el);

    function pos(e) { const r = cv.getBoundingClientRect(); return { x: e.clientX - r.left, y: e.clientY - r.top }; }
    function scratchAt(p) {
      ctx.globalCompositeOperation = 'destination-out';
      ctx.lineCap = 'round'; ctx.lineJoin = 'round'; ctx.lineWidth = 34;
      ctx.beginPath();
      if (last) { ctx.moveTo(last.x, last.y); ctx.lineTo(p.x, p.y); ctx.stroke(); }
      ctx.arc(p.x, p.y, 17, 0, Math.PI * 2); ctx.fill();
      last = p;
      if (++checks % 8 === 0) checkClear();
    }
    function checkClear() {
      const data = ctx.getImageData(0, 0, cv.width, cv.height).data;
      let clear = 0, total = 0;
      for (let i = 3; i < data.length; i += 4 * 24) { total++; if (data[i] === 0) clear++; }
      if (clear / total > 0.42) reveal();
    }
    function reveal() {
      if (revealed) return; revealed = true;
      el.classList.add('revealed');
      sparkles(el);
    }
    el._reveal = reveal;
    cv.addEventListener('pointerdown', (e) => {
      drawing = true; moved = 0; last = pos(e);
      cv.setPointerCapture(e.pointerId);
    });
    cv.addEventListener('pointermove', (e) => {
      if (!drawing) return;
      const p = pos(e);
      moved += Math.hypot(p.x - last.x, p.y - last.y);
      scratchAt(p);
    });
    const end = () => {
      if (!drawing) return; drawing = false; last = null;
      if (moved < 6) reveal(); // a tap reveals everything
      else checkClear();
    };
    cv.addEventListener('pointerup', end);
    cv.addEventListener('pointercancel', end);
    cv.addEventListener('keydown', (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); reveal(); } });
    cv.tabIndex = 0; cv.setAttribute('role', 'button'); cv.setAttribute('aria-label', 'Reveal translation');
  }
  function sparkles(el) {
    if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    const r = el.getBoundingClientRect();
    for (let i = 0; i < 8; i++) {
      const s = document.createElement('span');
      s.className = 'sparkle'; s.textContent = ['✨', '⭐', '💫'][i % 3];
      s.style.left = Math.random() * r.width + 'px'; s.style.top = Math.random() * r.height + 'px';
      s.style.setProperty('--dx', (Math.random() - 0.5) * 60 + 'px'); s.style.setProperty('--dy', -Math.random() * 40 - 10 + 'px');
      el.appendChild(s); setTimeout(() => s.remove(), 900);
    }
  }
  const scratchIO = 'IntersectionObserver' in window ? new IntersectionObserver((ents) => {
    ents.forEach((e) => { if (e.isIntersecting) { initScratch(e.target); scratchIO.unobserve(e.target); } });
  }, { rootMargin: '200px' }) : null;
  function armScratches(root = view) {
    $$('[data-scratch]', root).forEach((el) => (scratchIO ? scratchIO.observe(el) : initScratch(el)));
  }

